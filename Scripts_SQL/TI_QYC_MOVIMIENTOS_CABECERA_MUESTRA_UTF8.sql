 ,A.NUM_REQUERIMIENTO  
 ,A.NUM_OT_PIGMENTO  
 ,ISNULL(A.SER_DOCUM, '') AS SER_DOCUM  
 ,ISNULL(A.NUM_DOCUM, '') AS NUM_DOCUM  
