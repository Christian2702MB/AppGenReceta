SELECT A.COD_ALMACEN  
 ,A.NUM_MOVSTK  
 ,A.FEC_MOVSTK  
 ,A.NUM_GUIA  
 ,A.SER_ORDCOMP + A.COD_ORDCOMP AS ORDEN_COMPRA  
 ,A.COD_PROVEEDOR  
 ,ISNULL(C.DES_PROVEEDOR, '') AS PROVEEDOR  
 ,A.COD_CLIENTE  
 ,ISNULL(E.ABR_CLIENTE, '') AS ABR_CLIENTE  
 ,A.COD_TIPMOV AS TIP_MOV  
 ,B.DES_TIPMOV AS NOMBRE_MOV  
 ,A.COD_ORDTRA  
 ,A.COD_CENCOST  
 ,ISNULL(D.DES_CENCOST, '') AS CENTRO_COSTO  
 ,A.FEC_CREACION  
 ,A.SER_ORDCOMP  
 ,A.COD_ORDCOMP  
 ,A.OBSERVACIONES  
 ,A.NUM_REQUERIMIENTO  
 ,A.NUM_OT_PIGMENTO  
 ,ISNULL(A.SER_DOCUM, '') AS SER_DOCUM  
 ,ISNULL(A.NUM_DOCUM, '') AS NUM_DOCUM  
 ,ISNULL(A.SER_DOCUM, '') + ' - ' + ISNULL(A.NUM_DOCUM, '') AS FACTURA  
 ,ISNULL(A.USUARIO_VALORIZO, '') AS USUARIO_VALORIZO  
 ,A.SER_PARTE_SALIDA  
 ,A.NUMERO_PARTE_SALIDA  
 ,A.RUC_TRANSPORTISTA  
 ,A.NUM_PLACA  
 ,A.COD_LICENCIA_TRANSP  
 ,A.NRO_CONOS_HILOS_COSER  
 ,LTRIM(RTRIM(A.Cod_Usuario)) as 'USUARIO'
FROM #MOVISTK AS A  
INNER JOIN LG_TIPOSMOV AS B ON A.COD_TIPMOV = B.COD_TIPMOV  
LEFT OUTER JOIN LG_PROVEEDOR AS C ON A.COD_PROVEEDOR = C.COD_PROVEEDOR  
LEFT OUTER JOIN TX_CENCOSTO AS D ON A.COD_CENCOST = D.COD_CENCOST  
LEFT OUTER JOIN TX_CLIENTE AS E ON A.COD_CLIENTE = E.COD_CLIENTE_TEX  
ORDER BY A.FEC_MOVSTK  
 ,A.NUM_MOVSTK  
  
