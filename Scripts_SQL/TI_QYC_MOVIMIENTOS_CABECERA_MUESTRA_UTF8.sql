ALTER PROCEDURE [dbo].[TI_QYC_MOVIMIENTOS_CABECERA_MUESTRA]   
@OPCION AS CHAR(1)  
,@COD_ALMACEN AS COD_ALMACEN  
,@NUM_MOVSTK AS NUM_MOVSTK  
,@FEC_MOVSTK AS DATETIME  
,@NUM_GUIA AS CHAR(15)  
,@COD_ORDTRA AS COD_ORDTRA = ''   
AS /* OPCION 1, FECHA, 2 MOVIMIENTO, 3 GUIA */  
  
SET NOCOUNT ON  
SET ANSI_NULLS ON  
SET QUOTED_IDENTIFIER ON  
  
SELECT TOP 0 *  
INTO #MOVISTK  
FROM LG_MOVISTK  
WHERE COD_ALMACEN = ''  
  
DELETE #MOVISTK  
  
IF @OPCION = '1'  
BEGIN  
 INSERT #MOVISTK  
 SELECT *  
 FROM LG_MOVISTK  
 WHERE COD_ALMACEN = @COD_ALMACEN  
  AND FEC_MOVSTK = @FEC_MOVSTK  
END  
  
IF @OPCION = '2'  
BEGIN  
 INSERT #MOVISTK  
 SELECT *  
 FROM LG_MOVISTK  
 WHERE COD_ALMACEN = @COD_ALMACEN  
  AND NUM_MOVSTK = @NUM_MOVSTK  
END  
  
IF @OPCION = '3'  
BEGIN  
 INSERT #MOVISTK  
 SELECT *  
 FROM LG_MOVISTK  
 WHERE COD_ALMACEN = @COD_ALMACEN  
  AND NUM_GUIA LIKE '%' + @NUM_GUIA + '%'  
END  
  
IF @OPCION = '4'  
BEGIN  
 INSERT #MOVISTK  
 SELECT *  
 FROM LG_MOVISTK  
 WHERE COD_ALMACEN = @COD_ALMACEN  
  AND COD_ORDTRA LIKE '%' + @COD_ORDTRA + '%'  
END  
  
